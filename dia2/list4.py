# Dividir cadenas

cadena = "Hola Mundo Python"

print(cadena)
lista = cadena.split(" ") # Division de la cadena con split
print(lista) # ['Hola', 'Mundo', 'Python']

# Dividr cadenas con multiples espacios
cadena = "Hola, Mundo, Python"
lista = cadena.split(", ")
print(lista) # ['Hola', 'Mundo', 'Python']

